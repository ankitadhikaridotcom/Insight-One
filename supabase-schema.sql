        RETURN public.fn_response_error('fn_engagement_list', 'UNAUTHORIZED', v_ctx->>'error_message', 403, NULL, NULL, v_ctx);
    END IF;

    v_tenant_id := (v_ctx->>'tenant_id')::INTEGER;

    SELECT jsonb_agg(
        jsonb_build_object(
            'id', eg.id,
            'client_id', eg.client_id,
