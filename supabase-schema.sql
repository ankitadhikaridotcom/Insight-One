CREATE OR REPLACE FUNCTION public.fn_client_list(
    p_search TEXT DEFAULT NULL,
    p_status TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_ctx JSONB;
    v_tenant_id INTEGER;
    v_data JSONB;
BEGIN
    v_ctx := public.fn_get_request_context('fn_client_list');
    IF NOT (v_ctx->>'is_authorized')::BOOLEAN THEN
        RETURN public.fn_response_error('fn_client_list', 'UNAUTHORIZED', v_ctx->>'error_message', 403, NULL, NULL, v_ctx);
    END IF;

    v_tenant_id := (v_ctx->>'tenant_id')::INTEGER;

    SELECT jsonb_agg(
        jsonb_build_object(
            'id', c.id,
            'name', c.name,
            'company', c.company,
            'email', c.email,
            'phone', c.phone,
            'website', c.website,
            'industry', c.industry,
            'status', c.status,
            'value', c.value,
            'notes', c.notes,
            'tenant_id', c.tenant_id,
            'created_at', c.created_at,
            'updated_at', c.updated_at
        ) ORDER BY c.created_at DESC
    )
    INTO v_data
    FROM public.clients c
    WHERE c.tenant_id = v_tenant_id
      AND c.is_active = true
      AND (p_status IS NULL OR p_status = 'ALL' OR c.status = p_status)
      AND (
          p_search IS NULL OR p_search = '' 
          OR c.name ILIKE '%' || p_search || '%'
          OR c.company ILIKE '%' || p_search || '%'
          OR c.email ILIKE '%' || p_search || '%'
      );

    RETURN public.fn_response_success(COALESCE(v_data, '[]'::jsonb), NULL, 'Clients retrieved');
END;
$$;

